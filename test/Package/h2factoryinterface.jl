module H2FactoryInterfaceTest
using Test
using MultilevelKernelInterpolation
using H2Factory

# MultilevelKernelInterpolation participates in H2Factory by adding methods to H2Factory's own functions, spread over the
# translation, moment, operator and core files. This pins BOTH the set of functions extended and HOW
# MANY methods each carries.
#
# THE COUNT IS THE POINT, not the set. Pinning only the function set catches a whole extension point
# disappearing, but not a deleted specialization: drop MultilevelKernelInterpolation's Toeplitz `modulate_in!` and the name is
# still in the set, so the test stays green while that path silently falls back to a generic that
# does not reduce anything. The upcoming `Interfaces` migration re-homes these declarations, which is
# exactly when a lost specialization is easiest to cause and hardest to notice.
#
# WHY THIS EXISTS AT ALL. A static scan of MultilevelKernelInterpolation's source found 42 extended generics and was wrong in
# both directions: it missed `conjmul!` entirely, all 42 methods of it, because they are generated by
# `@linkmomenttocollection` and never appear as text. Whatever is counted here has to be counted from
# the LOADED package, never from the source.
#
# Both halves are derived from the loaded package. The literal below is the reviewed snapshot they
# are compared against, so a deliberate change is a one-line diff here and an accidental one fails.
const EXTENDEDH2FACTORYMETHODS = Dict(
    # The I2O coupling kernel, 2 methods (one per accumulation mode, each generic in direction).
    # Was 6: `i2otranslation!`/`o2itranslation!`/`adjointo2itranslation!` at 2 arities each, before
    # #180 made direction and accumulation arguments. Those six also carried a hand-written
    # `assertnosymmetry` call apiece, because they were defined at the guarded entry's own arity and
    # therefore shadowed it (#172); a kernel cannot shadow the entry, so the guard is now reached
    # once, from H2Factory, and `assertnosymmetry` below is the single forwarding declaration.
    :applycouplingkernel! => 2,
    :assertnosymmetry => 1,
    :borrowbuffer => 2,
    :buildi2ichannels => 2,
    :buildi2ochannel => 2,
    :buildmoments => 2,
    :buildo2ochannels => 2,
    :buildvectorbuffers => 2,
    :conjmul! => 42,
    :i2otrait => 1,
    :i2otranslator => 6,
    :isgalerkinsymmetric => 4,
    # NEW, and deliberately so. H2Factory removed its shared `leafmul` default for the ADJOINT
    # orientation: the adjoint conjugates both leaf collections on top of the coupling's transpose,
    # which is a no-op only when they are REAL, and no generic can tell. MultilevelKernelInterpolation's collections are real
    # (its map is `ComplexF64` while the leaf blocks are `Float64`, measured), so both cores now
    # declare the plain matvec explicitly instead of inheriting it. One method per core.
    :leafmul => 2,
    :minrelevantlevel => 2,
    :modulate_in! => 2,
    :modulate_out! => 2,
    :modulation => 1,
    :operator => 7,
    :schedulinglevels => 2,
    :storetrait => 1,
    :takefftplan! => 1,
    :takeifftplan! => 1,
    :testaggregationplan => 2,
    :testdisaggregationplan => 2,
    :testi2itranslator => 2,
    :testmomentcollections => 2,
    :testo2otranslator => 2,
    :trialaggregationplan => 2,
    :trialdisaggregationplan => 2,
    :triali2itranslator => 2,
    :trialmomentcollections => 2,
    :trialo2otranslator => 2,
    :verbose => 2,
    :α => 13,
)

# A method defined inside a submodule counts as MultilevelKernelInterpolation's, so walk up to the root module rather than
# comparing against `MultilevelKernelInterpolation` directly.
function belongstopackage(mod::Module)
    mod === MultilevelKernelInterpolation && return true
    parent = parentmodule(mod)
    return parent !== mod && belongstopackage(parent)
end

"""
    ish2factorygeneric(value) -> Bool

Whether `value` is a generic function H2Factory OWNS, as opposed to one it merely re-exports.

Two owners are valid, and they are named EXPLICITLY rather than accepted by walking the module tree.
`H2Factory.Interfaces` holds the declared extension protocol, so a generic migrated there is still
H2Factory's and must keep being counted; `H2Factory` itself owns everything not yet migrated.
Accepting any H2Factory submodule would weaken this: an implementation helper in some future
submodule would then be counted as protocol.

Without the `Interfaces` arm, every successfully migrated generic reads as having DISAPPEARED, and
the guard fires on the migration itself rather than on anything being lost.
"""
function ish2factorygeneric(value)
    value isa Function || return false
    return parentmodule(value) in (H2Factory, H2Factory.Interfaces)
end

"""
    extendedh2factorymethods()

Every function owned by `H2Factory` that MultilevelKernelInterpolation adds methods to, mapped to how many it adds.
"""
function extendedh2factorymethods()
    extended = Dict{Symbol,Int}()
    # `imported=true` IS REQUIRED, and its absence is silent. `names(M; all=true)` lists names
    # DEFINED in M and omits ones it imported, so every generic that moves into
    # `H2Factory.Interfaces` disappears from this enumeration and reads as zero methods. The
    # ownership predicate cannot save it: the name never reaches the predicate at all.
    #
    # It also admits H2Factory's imports from other packages (`AggregatePlan` and friends from
    # H2Trees), which is exactly what `ish2factorygeneric` then discards. The two work as a pair:
    # the keyword widens the enumeration to everything reachable, the predicate narrows it to what
    # H2Factory owns.
    for name in names(H2Factory; all=true, imported=true)
        isdefined(H2Factory, name) || continue
        value = getfield(H2Factory, name)
        # Skips functions H2Factory only re-exports: an extension of those is somebody else's seam.
        ish2factorygeneric(value) || continue
        count = sum(method -> belongstopackage(method.module), methods(value); init=0)
        count > 0 && (extended[name] = count)
    end

    return extended
end

@testset "H2Factory extension points" begin
    extended = extendedh2factorymethods()

    @testset "the set of extension points" begin
        # Split rather than a single equality so a failure names what changed. `collect` matters:
        # `setdiff` over two `KeySet`s returns a `Set`, which is never `== Symbol[]` even when empty.
        @test sort(
            collect(setdiff(keys(extended), keys(EXTENDEDH2FACTORYMETHODS))); by=string
        ) == Symbol[]
        @test sort(
            collect(setdiff(keys(EXTENDEDH2FACTORYMETHODS), keys(extended))); by=string
        ) == Symbol[]
    end

    @testset "the method count of each" begin
        # This is what catches a lost specialization rather than a lost function.
        for name in sort(collect(keys(EXTENDEDH2FACTORYMETHODS)); by=string)
            @test get(extended, name, 0) == EXTENDEDH2FACTORYMETHODS[name]
        end
        @test sum(values(extended)) == sum(values(EXTENDEDH2FACTORYMETHODS))
    end

    @testset "the enumeration is not vacuous" begin
        @test !isempty(extended)

        # THE MACRO-GENERATED SEAM. `conjmul!` carries more MultilevelKernelInterpolation methods than every other extension
        # point combined would suggest, and not one of them is visible in MultilevelKernelInterpolation's source: they come
        # from `@linkmomenttocollection`. It is the seam a text-based check cannot see, so it is the
        # one worth naming explicitly here.
        @test :conjmul! in keys(extended)
        @test extended[:conjmul!] > 30

        # The protocol families the upcoming migration moves, named so that a family vanishing in
        # one edit fails here rather than merely shifting a total.
        @test :modulate_in! in keys(extended)      # I2O modulation
        @test :modulate_out! in keys(extended)
        @test :takefftplan! in keys(extended)      # FFT plans
        @test :takeifftplan! in keys(extended)
        @test :borrowbuffer in keys(extended)      # buffer protocol
        @test :buildmoments in keys(extended)      # workspace construction
    end

    @testset "MultilevelKernelInterpolation adds no applycoupling! method" begin
        # `H2Factory.applycoupling!` is ORCHESTRATION: one method, in H2Factory, that owns the
        # `assertnosymmetry` guard before delegating to `applycouplingkernel!`. Dispatch cannot
        # prevent a downstream method at a concrete collection type from shadowing it and silently
        # skipping the refusal -- `BsplineI2OTranslationCollection` did precisely that under the
        # former protocol, which is why #172 needed six hand-written guard calls. So what is
        # enforceable is that no such method exists, pinned here rather than assumed.
        @test !any(m -> belongstopackage(m.module), methods(H2Factory.applycoupling!))
        @test :applycoupling! ∉ keys(extended)

        # And it DOES participate, through the kernel -- otherwise the assertion above would pass for
        # a package that had simply left the protocol.
        @test :applycouplingkernel! in keys(extended)
    end
end

end # module H2FactoryInterfaceTest
